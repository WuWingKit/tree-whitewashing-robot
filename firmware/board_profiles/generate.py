"""One source for PCB pinmap, STM32, and both ESP32 build variants.

Generate headers without flashing or changing the default physical wiring.
Run --check in verification to detect drift from pinmaps.json.
"""
import argparse, hashlib, json
from pathlib import Path
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
SOURCE=HERE/'pinmaps.json'
TARGETS=[ROOT/'firmware/remote_control/stm32/App/robot_pinmap.h',
         ROOT/'firmware/remote_control/esp32/RemoteControl/robot_pinmap.h',
         ROOT/'firmware/sensor_test/esp32/main/robot_pinmap.h']

def render(data):
    sha=hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    out=['/* Generated by firmware/board_profiles/generate.py; edit pinmaps.json. */',
         '#ifndef ROBOT_PINMAP_H','#define ROBOT_PINMAP_H',
         '#define ROBOT_WIRING_LEGACY 0','#define ROBOT_WIRING_PCB_V1 1','#define ROBOT_WIRING_PCB_V2 2',
         '#ifndef ROBOT_WIRING_PROFILE',
         '#error "ROBOT_WIRING_PROFILE is not defined: build with legacy(0) / pcb_v1(1) / pcb_v2(2) explicitly. See firmware/board_profiles/WIRING_PCB_V2.md"',
         '#endif',
         '#define ROBOT_PINMAP_SHA256 "'+sha+'"']
    for name,num in [('legacy',0),('pcb_v1',1),('pcb_v2',2)]:
        p=data['profiles'][name]
        pins=[p['uart']['stm_tx'],p['uart']['stm_rx'],p['estop']]
        pins += [m[k]for m in p['motor']for k in ['pwm','in1','in2']]
        pins += [t[k]for t in p['tof']for k in ['scl','sda']]
        if 'actuators' in p:
            a=p['actuators'];pins += [a[k] for k in ['step_pulse','step_direction','step_enable','servo','limit_low','limit_high']] + a['irf']
        assert len(pins)==len(set(pins)),(name,'GPIO conflict')
        assert [m['pwm']for m in p['motor']]==['PE9','PE11','PE13','PE14']
        assert p['uart']['stm_tx']=='PA2'and p['uart']['stm_rx']=='PA3'
        out+=['#if ROBOT_WIRING_PROFILE == '+str(num) if num==0 else '#elif ROBOT_WIRING_PROFILE == '+str(num),
              '#define ROBOT_PINMAP_NAME "'+name+'"']
        def gpio(key,pin):
            assert pin[0]=='P'and pin[1]in 'ABCDEFG'and 0<=int(pin[2:])<=15
            out.extend(['#define '+key+'_PORT GPIO'+pin[1],'#define '+key+'_PIN GPIO_PIN_'+pin[2:]])
        for i,m in enumerate(p['motor'],1):
            for k in ['pwm','in1','in2']:gpio('ROBOT_MOTOR'+str(i)+'_'+k.upper(),m[k])
        for i,t in enumerate(p['tof']):
            assert t['scl'][1]==t['sda'][1], 'software I2C driver needs one GPIO port per sensor'
            gpio('ROBOT_TOF'+str(i)+'_SCL',t['scl']);gpio('ROBOT_TOF'+str(i)+'_SDA',t['sda'])
        gpio('ROBOT_STM_UART_TX',p['uart']['stm_tx']);gpio('ROBOT_STM_UART_RX',p['uart']['stm_rx'])
        gpio('ROBOT_STOP',p['estop'])
        out.append('#define ROBOT_HAS_UPPER_ACTUATORS '+('1' if 'actuators' in p else '0'))
        if 'actuators' in p:
            for key in ['step_pulse','step_direction','step_enable','servo','limit_low','limit_high']:gpio('ROBOT_'+key.upper(),p['actuators'][key])
            for i,pin in enumerate(p['actuators']['irf'],1):gpio('ROBOT_IRF'+str(i),pin)
        out+=['#define ROBOT_ESP_UART_TX '+p['uart']['esp_tx'].removeprefix('GPIO'),
              '#define ROBOT_ESP_UART_RX '+p['uart']['esp_rx'].removeprefix('GPIO')]
    out+=['#else','#error Unsupported ROBOT_WIRING_PROFILE','#endif','#endif','']
    return '\n'.join(out)

def generate(check=False):
    data=json.loads(SOURCE.read_text(encoding='utf-8'))
    text=render(data)
    for path in TARGETS:
        if check:
            if not path.exists()or path.read_text(encoding='utf-8')!=text:raise SystemExit('Pinmap drift: '+str(path))
        else:path.write_text(text,encoding='utf-8')
    b=data['profiles']['legacy'];p=data['profiles']['pcb_v1']
    doc=['# PCB V1接线与固件配置（样板配置）','','接线配置建立于2026-11-10，PCB于2026-11-11完成原生导入、布线及规则检查。由`pinmaps.json`统一生成；现有车使用`legacy`，新PCB对应`pcb_v1`；构建时 `--profile` 为必填。尚未完成实物装配与供电/USB验证，不能给现有杜邦接线车直接烧录PCB配置。','',
         '|功能|现有杜邦接线 legacy|新载板 pcb_v1|','|---|---|---|']
    for old,new in zip(b['motor'],p['motor']):
        for key,tag in [('pwm','P'),('in1','IN1'),('in2','IN2')]:doc.append(f"|M{new['channel']} / {new['channel']}{tag}|{old[key]}|{new[key]}|")
    for i,(old,new)in enumerate(zip(b['tof'],p['tof'])):
        for key in ['scl','sda']:doc.append(f'|ToF{i} {key.upper()}|{old[key]}|{new[key]}|')
    doc+=['','UART均保持PA2 TX→GPIO18 RX，GPIO17 TX→PA3 RX，115200/8N1/3.3V TTL；原生USB仍为GPIO19/20。PE0软件停车输入保留。PWM仍为PE9/11/13/14的TIM1四通道。',
          '', '新增电机方向输出及PD11/PD12与板载SRAM/FSMC复用；两种固件均保持PG10高、禁止FSMC/SRAM和TFT初始化。三个软件I²C总线互不并联，INT/SHUT不接。',
          '', 'PCB上的AUX_3V3是独立传感器稳压输出，不接STM32或ESP32的板载3V3输出。两块主控的5V跳线在电脑USB供电时断开。相机VBUS来自各自Hub下行口，不并接SYS_5V。',
          '', '## 编译选择', '', '```powershell',
          'python firmware/board_profiles/generate.py --check',
          'python firmware/remote_control/tools/build_stm32.py --profile legacy',
          'python firmware/remote_control/tools/build_stm32.py --profile pcb_v1',
          'python firmware/remote_control/tools/build_integrated.py --profile pcb_v1',
          'python firmware/sensor_test/tools/build_esp32.py --profile pcb_v1', '```','',
          'STM32新PCB输出在`remote_control/stm32/build/pcb_v1/`；ESP32整合版输出在`remote_control/esp32/build/integrated/pcb_v1/`。当前杜邦接线车继续使用原目录中的legacy版本。只编译，不自动烧录。',
          '', '手动Keil/Arduino构建：`ROBOT_WIRING_PROFILE=0`为现有接线，`=1`为新PCB，`=2`为V4.x四层板。**必须显式指定**——未定义时头文件会直接`#error`，不再静默退回legacy，避免插错板子却编译通过。所有生成的`robot_pinmap.h`必须来自同一份JSON，不能逐份修改。','']
    path=HERE/'WIRING_PCB_V1.md';content='\n'.join(doc)
    if check:
        if not path.exists()or path.read_text(encoding='utf-8')!=content:raise SystemExit('Pinmap document drift')
    else:path.write_text(content,encoding='utf-8')
    print('Pinmap headers and wiring table '+('verified'if check else 'generated')+': '+str(len(TARGETS)))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true')
    generate(p.parse_args().check)
